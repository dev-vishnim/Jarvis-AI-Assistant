def handle_pending_confirmation(command):
    global pending_confirmation
    if pending_confirmation is None:
        return None
    text = normalize_command(command)
    yes_words = {"confirm", "yes", "yes do it", "proceed", "go ahead", "continue"}
    no_words = {"cancel", "no", "stop", "dont", "do not", "never mind"}
    if text in yes_words:
        action = pending_confirmation
        pending_confirmation = None
        try:
            if action["type"] == "browser_click":
                ok, msg = browser_click(action.get("target"))
                return msg if ok else msg
            if action["type"] == "browser_press":
                browser_page.keyboard.press(action.get("key", "Enter"))
                return "I performed the confirmed browser action."
            if action["type"] == "desktop_click":
                pyautogui.click(int(action["x"]), int(action["y"]))
                return "I performed the confirmed desktop click."
            if action["type"] == "desktop_press":
                keyboard.send(action.get("key", "enter"))
                return "I performed the confirmed key action."
        except Exception as exc:
            print("[Confirmation execution error]", exc)
            return "I couldn't complete the confirmed action."
        return "I couldn't identify the pending action."
    if text in no_words:
        pending_confirmation = None
        return "Cancelled. I didn't perform that action."
    return "I need your answer first. Say confirm to continue or cancel to stop."


def is_sleep_command(text):
    normalized = normalize_command(text)
    return normalized in {
        "go to sleep", "sleep jarvis", "stop listening", "end conversation",
        "goodbye jarvis", "goodbye", "thats all", "standby", "back to standby"
    }


def is_exit_command(text):
    normalized = normalize_command(text)
    return normalized in {
        "shutdown jarvis", "exit program", "close jarvis",
        "quit jarvis", "shut down the assistant", "exit jarvis"
    }


def ask_gemini(message):
    try:
        ui_state("THINKING")
        response = gemini_chat.send_message(message)
        return (response.text or "").strip() or "I couldn't generate a response just now."
    except Exception as exc:
        print("[Gemini chat error]", exc)
        return "I'm having trouble connecting to Gemini right now."


def process_command(command):
    global conversation_mode, running
    command = remove_polite_prefix(strip_wake_phrase(command)).strip()
    if not command:
        respond("I'm listening.")
        return

    if pending_confirmation is not None:
        result = handle_pending_confirmation(command)
        respond(result)
        return

    if is_exit_command(command):
        respond("Shutting down. Goodbye.")
        conversation_mode = False
        running = False
        return
    if is_sleep_command(command):
        respond("Okay. I'll return to standby.")
        conversation_mode = False
        return

    data = classify_intent(command)
    ui_state("THINKING" if data.get("intent") == "chat" else "EXECUTING")
    ui_log(f"Task: {data.get('intent', 'chat')} — {command}")
    result = execute_intent(data, command)
    if result is None:
        result = ask_gemini(command)
    if result:
        respond(result)


