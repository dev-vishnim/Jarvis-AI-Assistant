class HologramFace(QWidget):
    """Animated projection using the supplied geometric face artwork."""

    def __init__(self, parent=None):
        super().__init__(parent)
        self.state = "INITIALIZING"
        self.elapsed = 0.0
        self.phase = 0.0
        self.mouth_open = 1.2
        self.next_blink = 3.0
        self.blink_until = 0.0
        self.gaze_phase = 0.0
        self.scan_phase = 0.0
        self.face_pixmap = QPixmap(str(BASE_DIR / "assets" / "jarvis_face.jpg"))
        self.setMinimumSize(390, 500)
        self.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Expanding)
        self.timer = QTimer(self)
        self.timer.timeout.connect(self._animate)
        self.timer.start(33)

    def set_state(self, state):
        self.state = str(state).upper()
        self.update()

    def _animate(self):
        dt = 0.033
        self.elapsed += dt
        self.gaze_phase += dt * (0.9 if self.state == "LISTENING" else 0.42)
        self.scan_phase = (self.scan_phase + dt * (90 if self.state in {"THINKING", "EXECUTING"} else 42)) % 360

        if self.state == "SPEAKING":
            self.phase += dt * 11.5
            # Irregular multi-frequency movement feels less like a metronome.
            wave_a = abs(math.sin(self.phase))
            wave_b = abs(math.sin(self.phase * 1.73 + 0.6))
            self.mouth_open = 1.8 + wave_a * 10.5 + wave_b * 4.2
        else:
            self.mouth_open = max(1.0, self.mouth_open - 1.8)

        if self.elapsed >= self.next_blink:
            self.blink_until = self.elapsed + 0.13
            self.next_blink = self.elapsed + random.uniform(3.2, 6.0)
        self.update()

    def _draw_corner(self, painter, x, y, sx, sy, color):
        painter.setPen(QPen(color, 2.0))
        painter.drawLine(QPointF(x, y), QPointF(x + sx * 22, y))
        painter.drawLine(QPointF(x, y), QPointF(x, y + sy * 22))

