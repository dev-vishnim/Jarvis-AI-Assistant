def extract_query(text, patterns):
    value = str(text or "").strip()
    for pattern in patterns:
        value = re.sub(pattern, "", value, flags=re.I).strip(" ,.!?;:")
    return value


def extract_online_music_query(text, model_query=""):
    """Remove request wording while preserving the actual song/artist title."""
    raw = str(model_query or "").strip()
    original = str(text or "").strip()
    # Prefer Gemini's extracted title only when it is not just a copy of the command.
    if raw and normalized_words(raw) != normalized_words(original):
        candidate = raw
    else:
        candidate = original
    candidate = re.sub(r"^(please\s+)?(can you\s+)?", "", candidate, flags=re.I)
    candidate = re.sub(r"^(search for|look for|look up|search|find|play|watch|listen to|put on|start)\s+", "", candidate, flags=re.I)
    candidate = re.sub(r"^(a song|some music|a track|the song)\s+", "", candidate, flags=re.I)
    candidate = re.sub(r"\s+(and then play( it)?|then play( it)?|and play( it)?|and start playing)$", "", candidate, flags=re.I)
    candidate = re.sub(r"\s+(online|on youtube|from youtube|on you tube|from you tube|on the internet|on the web)$", "", candidate, flags=re.I)
    candidate = re.sub(r"^(a song|some music|a track|the song)$", "", candidate, flags=re.I)
    candidate = candidate.strip(" ,.!?;:")
    if candidate.lower() in {"online", "youtube", "you tube", "the internet", "the web"}:
        return ""
    return candidate


