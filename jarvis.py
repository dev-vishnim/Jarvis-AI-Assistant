def available_drives():
    drives = []
    try:
        mask = ctypes.windll.kernel32.GetLogicalDrives()
        for i in range(26):
            if mask & (1 << i):
                drive = f"{chr(65 + i)}:\\"
                if ctypes.windll.kernel32.GetDriveTypeW(drive) in (2, 3, 4):
                    drives.append(drive)
    except Exception:
        drives = [str(Path.home().anchor or Path.home())]
    return drives


def load_music_index():
    global music_library, music_index_ready
    if not MUSIC_INDEX_PATH.exists():
        return False
    try:
        data = json.loads(MUSIC_INDEX_PATH.read_text(encoding="utf-8"))
        tracks = data.get("tracks", [])
        if isinstance(tracks, list):
            music_library = [str(p) for p in tracks if isinstance(p, str)]
            music_index_ready = True
            print(f"[Music library] Loaded {len(music_library):,} tracks from cache.")
            return True
    except Exception as exc:
        print("[Music library cache error]", exc)
    return False


def scan_music_worker():
    global music_library, music_index_ready
    found = []
    drives = available_drives()
    last_report = time.time()
    folders = 0
    try:
        print("[Music scanner] Searching all available drives:", ", ".join(drives))
        for drive in drives:
            music_scan_status["current_drive"] = drive
            print("[Music scanner] Scanning", drive)
            for root, dirs, files in os.walk(drive, topdown=True, onerror=lambda _e: None):
                dirs[:] = [d for d in dirs if d.lower() not in SKIP_DIRS and not d.startswith(".")]
                folders += 1
                for filename in files:
                    if Path(filename).suffix.lower() in MUSIC_EXTENSIONS:
                        found.append(str(Path(root) / filename))
                if time.time() - last_report > 30:
                    music_scan_status["count"] = len(found)
                    print(f"[Music scanner] {folders:,} folders checked; {len(found):,} audio files found.")
                    last_report = time.time()
        temp = MUSIC_INDEX_PATH.with_suffix(".tmp")
        temp.write_text(json.dumps({
            "scanned_at": time.strftime("%Y-%m-%d %H:%M:%S"),
            "drives": drives, "tracks": found
        }, ensure_ascii=False), encoding="utf-8")
        temp.replace(MUSIC_INDEX_PATH)
        with music_scan_lock:
            music_library = found
            music_index_ready = True
            music_scan_status.update(running=False, done=True, error="", count=len(found), current_drive="")
        print(f"[Music scanner] Complete: {len(found):,} audio files.")
    except Exception as exc:
        with music_scan_lock:
            music_scan_status.update(running=False, done=True, error=str(exc), count=len(found), current_drive="")
        print("[Music scanner error]", exc)


def start_music_scan(force=False):
    global music_scan_thread
    with music_scan_lock:
        if music_scan_status["running"]:
            return "running"
        if music_index_ready and not force:
            return "ready"
        music_scan_status.update(running=True, done=False, error="", count=0, current_drive="")
        music_scan_thread = threading.Thread(target=scan_music_worker, daemon=True)
        music_scan_thread.start()
    return "started"


