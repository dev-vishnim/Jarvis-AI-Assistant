def builtin_app_launch(name):
    key = APP_ALIASES.get(str(name).strip().lower(), str(name).strip().lower())
    commands = {
        "notepad": ["notepad.exe"], "calculator": ["calc.exe"],
        "explorer": ["explorer.exe"], "taskmgr": ["taskmgr.exe"],
        "terminal": ["wt.exe"], "cmd": ["cmd.exe"],
        "powershell": ["powershell.exe"], "paint": ["mspaint.exe"],
        "snipping tool": ["snippingtool.exe"], "control": ["control.exe"]
    }
    if key == "opera":
        opera = find_opera()
        if not opera:
            return False
        subprocess.Popen([opera], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        return True
    if key == "vscode":
        candidates = [
            shutil.which("code"),
            str(Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Microsoft VS Code" / "Code.exe"),
            str(Path(os.environ.get("PROGRAMFILES", r"C:\Program Files")) / "Microsoft VS Code" / "Code.exe")
        ]
        exe = next((p for p in candidates if p and (shutil.which(p) or Path(p).is_file())), None)
        if exe:
            subprocess.Popen([exe])
            return True
        return False
    if key == "settings":
        os.startfile("ms-settings:")
        return True
    if key in commands:
        subprocess.Popen(commands[key])
        return True
    return None


def get_start_apps():
    global start_apps_cache
    if start_apps_cache is not None:
        return start_apps_cache
    result = []
    try:
        ps = (
            "Get-StartApps | Select-Object Name,AppID | "
            "ConvertTo-Json -Compress"
        )
        completed = subprocess.run(
            ["powershell.exe", "-NoProfile", "-Command", ps],
            capture_output=True, text=True, timeout=18,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0)
        )
        if completed.returncode == 0 and completed.stdout.strip():
            data = json.loads(completed.stdout)
            if isinstance(data, dict):
                data = [data]
            result = [x for x in data if isinstance(x, dict) and x.get("Name") and x.get("AppID")]
    except Exception as exc:
        print("[Start apps discovery warning]", exc)
    start_apps_cache = result
    return result


def get_shortcuts():
    global shortcut_cache
    if shortcut_cache is not None:
        return shortcut_cache
    roots = [
        Path(os.environ.get("APPDATA", "")) / "Microsoft" / "Windows" / "Start Menu" / "Programs",
        Path(os.environ.get("PROGRAMDATA", r"C:\ProgramData")) / "Microsoft" / "Windows" / "Start Menu" / "Programs",
        Path.home() / "Desktop",
        Path(os.environ.get("PUBLIC", r"C:\Users\Public")) / "Desktop"
    ]
    shortcuts = []
    for root in roots:
        if not root.exists():
            continue
        try:
            for path in root.rglob("*.lnk"):
                shortcuts.append(path)
        except Exception:
            pass
    shortcut_cache = shortcuts
    return shortcuts


def best_name_match(query, names):
    q = re.sub(r"[^a-z0-9 ]", " ", query.lower()).strip()
    q = re.sub(r"\s+", " ", q)
    best = None
    best_score = 0.0
    for item in names:
        name = re.sub(r"[^a-z0-9 ]", " ", str(item).lower()).strip()
        name = re.sub(r"\s+", " ", name)
        if not name:
            continue
        score = SequenceMatcher(None, q, name).ratio()
        if q == name:
            score = 1.0
        elif q in name or name in q:
            score = max(score, 0.88)
        if score > best_score:
            best, best_score = item, score
    return best, best_score


def launch_any_app(target):
    target = str(target or "").strip()
    if not target:
        return "Which application should I open?"
    try:
        builtin = builtin_app_launch(target)
        if builtin is True:
            return f"Opening {target}."
        if builtin is False:
            # Continue to Start Menu discovery in case the built-in path was absent.
            pass

        apps = get_start_apps()
        if apps:
            match, score = best_name_match(target, [x["Name"] for x in apps])
            if match and score >= 0.72:
                entry = next(x for x in apps if x["Name"] == match)
                app_id = str(entry["AppID"])
                subprocess.Popen(["explorer.exe", f"shell:AppsFolder\\{app_id}"])
                return f"Opening {match}."

        shortcuts = get_shortcuts()
        names = [p.stem for p in shortcuts]
        match, score = best_name_match(target, names)
        if match and score >= 0.70:
            path = next(p for p in shortcuts if p.stem == match)
            os.startfile(str(path))
            return f"Opening {match}."

        # App Paths registry entries can expose apps that have no Start Menu shortcut.
        if winreg is not None:
            for hive in (winreg.HKEY_CURRENT_USER, winreg.HKEY_LOCAL_MACHINE):
                key_path = r"SOFTWARE\Microsoft\Windows\CurrentVersion\App Paths"
                try:
                    with winreg.OpenKey(hive, key_path) as root:
                        count = winreg.QueryInfoKey(root)[0]
                        candidates = []
                        for i in range(count):
                            sub = winreg.EnumKey(root, i)
                            try:
                                with winreg.OpenKey(root, sub) as app_key:
                                    exe, _ = winreg.QueryValueEx(app_key, None)
                                    candidates.append((sub, exe))
                            except Exception:
                                continue
                        match, score = best_name_match(target, [Path(x[0]).stem for x in candidates])
                        if match and score >= 0.75:
                            exe = next(x[1] for x in candidates if Path(x[0]).stem == match)
                            if Path(exe).is_file():
                                os.startfile(exe)
                                return f"Opening {match}."
                except Exception:
                    continue
        return f"I couldn't find an installed application matching {target}. Try its name as shown in the Windows Start menu."
    except Exception as exc:
        print("[App launch error]", exc)
        return f"I couldn't open {target}."


