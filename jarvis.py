    if intent == "create_folder":
        return create_folder(target or query or original)
    if intent == "volume_up":
        return "Volume increased." if media_key("volume up") else "I couldn't change the volume."
    if intent == "volume_down":
        return "Volume decreased." if media_key("volume down") else "I couldn't change the volume."
