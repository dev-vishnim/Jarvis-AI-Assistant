def find_opera():
    local = os.environ.get("LOCALAPPDATA", "")
    pf = os.environ.get("PROGRAMFILES", r"C:\Program Files")
    pf86 = os.environ.get("PROGRAMFILES(X86)", r"C:\Program Files (x86)")
    candidates = [
        shutil.which("opera"),
        str(Path(local) / "Programs" / "Opera" / "opera.exe"),
        str(Path(local) / "Programs" / "Opera" / "launcher.exe"),
        str(Path(local) / "Programs" / "Opera GX" / "opera.exe"),
        str(Path(local) / "Programs" / "Opera GX" / "launcher.exe"),
        str(Path(pf) / "Opera" / "opera.exe"),
        str(Path(pf) / "Opera" / "launcher.exe"),
        str(Path(pf86) / "Opera" / "opera.exe"),
        str(Path(pf86) / "Opera" / "launcher.exe"),
        str(Path(pf) / "Opera GX" / "opera.exe")
    ]
    for item in candidates:
        if item and Path(item).is_file():
            return str(Path(item))
    return None


def ensure_browser():
    global playwright_driver, browser_context, browser_page
    with browser_lock:
        if sync_playwright is None:
            return False
        try:
            if browser_context is not None:
                pages = browser_context.pages
                if pages:
                    browser_page = pages[-1]
                    if not browser_page.is_closed():
                        return True
        except Exception:
            browser_context = None
            browser_page = None
        opera = find_opera()
        if not opera:
            print("[Browser] Opera executable was not found.")
            return False
        try:
            if playwright_driver is None:
                playwright_driver = sync_playwright().start()
            browser_context = playwright_driver.chromium.launch_persistent_context(
                user_data_dir=str(BROWSER_PROFILE),
                executable_path=opera,
                headless=False,
                no_viewport=True,
                args=["--start-maximized", "--disable-blink-features=AutomationControlled"]
            )
            pages = browser_context.pages
            browser_page = pages[0] if pages else browser_context.new_page()
            return True
        except Exception as exc:
            print("[Browser automation error]", exc)
            browser_context = None
            browser_page = None
            return False


def safe_http_url(url):
    value = str(url or "").strip()
    if not value:
        return None
    if not re.match(r"^https?://", value, flags=re.I):
        if re.match(r"^[a-z0-9.-]+\.[a-z]{2,}([/:?#].*)?$", value, flags=re.I):
            value = "https://" + value
        else:
            return None
    parsed = urlparse(value)
    if parsed.scheme not in {"http", "https"} or not parsed.netloc:
        return None
    return value


def open_url_external(url):
    try:
        opera = find_opera()
        if opera:
            subprocess.Popen([opera, url], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        else:
            webbrowser.open_new_tab(url)
        return True
    except Exception as exc:
        print("[Open URL error]", exc)
        return False


def browser_navigate(url):
    url = safe_http_url(url)
    if not url:
        return False, "That does not look like a safe web address."
    if ensure_browser():
        try:
            browser_page.goto(url, wait_until="domcontentloaded", timeout=30000)
            browser_page.wait_for_timeout(900)
            return True, f"Opened {browser_page.title()}"
        except Exception as exc:
            print("[Navigation error]", exc)
            return False, "I couldn't finish loading that page."
    if open_url_external(url):
        return True, "Opened the page in Opera. Browser automation is unavailable for this session."
    return False, "I couldn't open the website."


