    play_words = any(w in low for w in ("play", "put on", "start"))
    search_words = any(w in low for w in ("search", "find", "look for", "look up"))

    if (has_music or online) and play_words:
        result.update(intent="play_youtube" if online else "play_local_music", query=text)
        return result
    if "youtube" in low and play_words:
        result.update(intent="play_youtube", query=text)
        return result
    if "youtube" in low and search_words:
        result.update(intent="search_youtube", query=text)
        return result
    if has_music and search_words and not online:
        result.update(intent="search_local_music", query=text)
        return result
    if "google" in low and search_words:
        result.update(intent="search_google", query=text)
        return result
    if re.match(r"^(play|put on|start)\s+", low) and not online:
        result.update(intent="play_local_music", query=text)
        return result
