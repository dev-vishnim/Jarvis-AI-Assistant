def find_files(query, limit=8):
    query = re.sub(r"[^a-z0-9 ._-]", "", str(query).lower()).strip()
    if not query:
        return []
    found = []
    for root in user_search_roots():
        for current, dirs, files in os.walk(root, topdown=True, onerror=lambda _e: None):
            dirs[:] = [d for d in dirs if d.lower() not in SKIP_DIRS and not d.startswith(".")]
            for filename in files:
                stem = Path(filename).stem.lower()
                score = SequenceMatcher(None, query, stem).ratio()
                if query in stem:
                    score = max(score, 0.92)
                if score >= 0.48:
                    found.append((score, Path(current) / filename))
    found.sort(key=lambda item: item[0], reverse=True)
    return [path for _, path in found[:limit]]


