def listen(duration):
    if whisper_model is None:
        return ""
    try:
        ui_state("LISTENING")
        audio = sd.rec(
            int(duration * SAMPLE_RATE), samplerate=SAMPLE_RATE,
            channels=1, dtype="float32"
        )
        sd.wait()
        audio = np.asarray(audio, dtype=np.float32).flatten()
        if not audio.size:
            return ""
        level = float(np.sqrt(np.mean(np.square(audio))))
        if level < MIN_AUDIO_LEVEL:
            return ""
        segments, _ = whisper_model.transcribe(
            audio, language="en", beam_size=1,
            condition_on_previous_text=False, vad_filter=True
        )
        text = " ".join(s.text.strip() for s in segments).strip()
        if text:
            print("\nYOU:", text)
            ui_user(text)
            ui_state("THINKING")
        return text
    except Exception as exc:
        print("[Microphone error]", exc)
        time.sleep(0.35)
        return ""


def normalized_words(text):
    return re.sub(r"[^a-z0-9 ]", " ", str(text).lower()).split()


def wake_position(text):
    words = normalized_words(text)
    for i in range(len(words)):
        if words[i] == "jarvis":
            if i == 0:
                return i
            if words[i - 1] in {"hey", "hi", "hello"}:
                return i - 1
            if SequenceMatcher(None, words[i], "jarvis").ratio() >= 0.80:
                return i
        if i + 1 < len(words):
            pair = words[i] + " " + words[i + 1]
            if SequenceMatcher(None, pair, "hey jarvis").ratio() >= 0.78:
                return i
    return -1


def wake_word_detected(text):
    return wake_position(text) >= 0


def strip_wake_phrase(text):
    pos = wake_position(text)
    if pos < 0:
        return str(text).strip()
    words = str(text).split()
    # Remove the wake phrase from the original transcript approximately.
    normalized = normalized_words(text)
    raw_words = str(text).split()
    if len(raw_words) == len(normalized):
        return " ".join(raw_words[pos + (2 if pos + 1 < len(normalized) and normalized[pos] in {"hey", "hi", "hello"} else 1):]).strip(" ,.!?-")
    return str(text).strip()


def remove_polite_prefix(text):
    patterns = [
        r"^(please\s+)", r"^(can|could|would) you\s+",
        r"^(jarvis\s+)", r"^(i want you to\s+)",
        r"^(i would like you to\s+)", r"^(i'd like you to\s+)"
    ]
    result = str(text).strip()
    changed = True
    while changed:
        changed = False
        for pattern in patterns:
            updated = re.sub(pattern, "", result, flags=re.I)
            if updated != result:
                result = updated.strip()
                changed = True
                break
    return result


def normalize_command(text):
    return " ".join(normalized_words(remove_polite_prefix(strip_wake_phrase(text))))


