def cleanup_backend():
    global browser_context, playwright_driver, gemini_client
    try:
        if browser_context is not None:
            browser_context.close()
    except Exception:
        pass
    browser_context = None
    try:
        if playwright_driver is not None:
            playwright_driver.stop()
    except Exception:
        pass
    playwright_driver = None
    try:
        if pygame is not None and pygame.mixer.get_init():
            pygame.mixer.music.stop()
            pygame.mixer.quit()
    except Exception:
        pass
    try:
        if gemini_client is not None:
            gemini_client.close()
    except Exception:
        pass


def voice_worker():
    global whisper_model, gemini_client, gemini_chat
    global conversation_mode, running

    print("=" * 58)
    print("                 JARVIS INITIALIZING")
    print("=" * 58)
    ui_state("INITIALIZING")
    load_dotenv(ENV_PATH)
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        message = f"GEMINI_API_KEY not found in {ENV_PATH}. Add your key to the .env file."
        print("[Startup error]", message)
        ui_bridge.backend_ready.emit(False, message)
        ui_log(message)
        return

    try:
        gemini_client = genai.Client(api_key=api_key)
        gemini_chat = gemini_client.chats.create(
            model=MODEL,
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_INSTRUCTION,
                max_output_tokens=300,
                temperature=0.6
            )
        )
        print("Gemini connected:", MODEL)
        ui_log(f"Gemini connected: {MODEL}")
    except Exception as exc:
        message = f"Gemini initialization failed: {exc}"
        print("[Startup error]", message)
        ui_bridge.backend_ready.emit(False, message)
        ui_log(message)
        return

    print("Loading Whisper speech recognition…")
    ui_log("Loading Whisper speech recognition model…")
    try:
        whisper_model = WhisperModel("base", device="cpu", compute_type="int8")
    except Exception as exc:
        message = f"Whisper initialization failed: {exc}"
        print("[Startup error]", message)
        ui_bridge.backend_ready.emit(False, message)
        ui_log(message)
        return

    if pygame is not None:
        init_music_player()
    load_music_index()

    try:
        keyboard.add_hotkey("esc", interrupt_speech)
        print("ESC speech interruption enabled.")
    except Exception as exc:
        print("[ESC hook warning]", exc)
        ui_log(f"ESC hotkey unavailable: {exc}. Use the INTERRUPT button.")

    details = (
        f"Online · Gemini {MODEL} · Whisper ready · "
        f"Opera {'detected' if find_opera() else 'not detected'} · "
        f"Playwright {'available' if sync_playwright else 'not installed'}"
    )
    print("\n" + "=" * 58)
    print("                  JARVIS IS ONLINE")
    print("=" * 58)
    print(details)
    print("Say 'Hey Jarvis' to start. Press ESC to interrupt speech.")
    ui_bridge.backend_ready.emit(True, details)
    ui_state("STANDBY")
    speak("Jarvis is online. Say Hey Jarvis whenever you need me.")

    last_activity = 0.0
    try:
        while running and not stop_event.is_set():
            # Commands typed into the UI use the same execution pipeline as voice.
            try:
                typed_command = command_queue.get_nowait()
            except queue.Empty:
                typed_command = "__NO_COMMAND__"

            if typed_command is None:
                break
            if typed_command != "__NO_COMMAND__":
                conversation_mode = True
                last_activity = time.monotonic()
                process_command(typed_command)
                last_activity = time.monotonic()
                continue

            if not conversation_mode:
                ui_state("STANDBY")
                heard = listen(WAKE_DURATION)
                if wake_word_detected(heard):
                    conversation_mode = True
                    last_activity = time.monotonic()
                    command = strip_wake_phrase(heard)
                    if command:
                        process_command(command)
                        last_activity = time.monotonic()
                    else:
                        respond("I'm listening.")
            else:
                if time.monotonic() - last_activity >= CONVERSATION_TIMEOUT:
                    conversation_mode = False
                    respond("Conversation timed out. Returning to standby.")
                    continue
                heard = listen(FOLLOWUP_DURATION)
                if heard:
                    last_activity = time.monotonic()
                    process_command(heard)
                    last_activity = time.monotonic()
    except Exception as exc:
        print("[Voice worker error]", exc)
        ui_log(f"Voice worker error: {exc}")
        ui_state("ERROR")
    finally:
        interrupt_speech()
        cleanup_backend()
        ui_state("OFFLINE")
        print("\nJARVIS has shut down.")


def main():
    global ui_bridge, voice_thread, running

    app = QApplication(sys.argv)
    app.setApplicationName("JARVIS")
    app.setOrganizationName("JARVIS Personal Assistant")
    app.setStyle("Fusion")

    ui_bridge = JarvisUiBridge()
    window = JarvisWindow(ui_bridge)
    window.show()

    running = True
    stop_event.clear()
    voice_thread = threading.Thread(target=voice_worker, name="JarvisVoiceEngine", daemon=True)
    voice_thread.start()

    exit_code = app.exec()
    running = False
    stop_event.set()
    command_queue.put(None)
    interrupt_speech()
    if voice_thread is not None and voice_thread.is_alive():
        voice_thread.join(timeout=6.0)
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
