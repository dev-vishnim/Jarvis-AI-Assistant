def play_youtube(query):
    """Search YouTube, open the first real video result, and attempt to click Play."""
    query = str(query or "").strip()
    if not query:
        return "Which song or video should I play online?"
    if not ensure_browser():
        opened = open_url_external("https://www.youtube.com/results?search_query=" + quote_plus(query))
        if opened:
            return "I opened YouTube search results, but automatic playback needs the Playwright browser package."
        return "I couldn't open YouTube."
    try:
        search_url = "https://www.youtube.com/results?search_query=" + quote_plus(query)
        browser_page.goto(search_url, wait_until="domcontentloaded", timeout=30000)
        browser_page.wait_for_selector("ytd-video-renderer a#video-title", timeout=20000)
        result = browser_page.locator("ytd-video-renderer a#video-title").first
        title = (result.inner_text(timeout=4000) or "the first matching result").strip()
        href = result.get_attribute("href")
        if href and href.startswith("/"):
            href = "https://www.youtube.com" + href
        if href and "/watch" in href:
            # Clicking is preferred because it counts as a browser user gesture.
            try:
                result.click(timeout=7000)
            except Exception:
                browser_page.goto(href, wait_until="domcontentloaded", timeout=30000)
        else:
            return "I found YouTube results, but couldn't identify a playable video link."
        browser_page.wait_for_timeout(2500)
        try:
            video = browser_page.locator("video").first
            video.wait_for(state="attached", timeout=12000)
            state = video.evaluate("v => ({paused: v.paused, ready: v.readyState})")
            if state.get("paused"):
                for selector in ("button.ytp-large-play-button", "button.ytp-play-button"):
                    button = browser_page.locator(selector).first
                    try:
                        if button.count() and button.is_visible():
                            button.click(timeout=3500)
                            break
                    except Exception:
                        pass
                browser_page.wait_for_timeout(1800)
                state = video.evaluate("v => ({paused: v.paused, ready: v.readyState})")
            if not state.get("paused"):
                return f"Playing {title} on YouTube."
            return f"I opened {title} on YouTube, but playback is still paused. Press the Play button once."
        except Exception:
            return f"I opened {title} on YouTube. The site may require you to press Play or sign in."
    except Exception as exc:
        print("[YouTube playback error]", exc)
        return "I couldn't automatically start the YouTube video. I left the search results open."


